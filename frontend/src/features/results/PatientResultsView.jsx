import React, { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import {
  CheckCircle2,
  AlertTriangle,
  HeartHandshake,
  ShieldAlert,
  ChevronDown,
  ChevronUp,
  Activity,
  Stethoscope,
  Info,
  Clock,
  ExternalLink,
  HelpCircle,
  AlertCircle,
  Layers,
  MapPin,
  ClipboardList,
  Copy,
  Check,
  ArrowRight,
} from 'lucide-react';
import ScoreGauge from '../../components/ScoreGauge';
import { getConditionLaymanDetails } from '../../utils/conditionLaymanMap';

/**
 * PatientResultsView — Everyday User Experience
 * Color Palette: Image 3 (Healing Forest & Mint)
 * #051F20 | #0B2B26 | #163832 | #235347 | #8EB69B | #DAF1DE
 */
export default function PatientResultsView({ analysisData, onView3D }) {
  const [showOtherConditions, setShowOtherConditions] = useState(false);
  const [copiedQuestions, setCopiedQuestions] = useState(false);

  const {
    possibleConditions = [],
    storyline = {},
    bodyLocalization = {},
  } = analysisData;

  // Single Source of Truth: exact top condition predicted by diagnostic engine
  const topCondition = possibleConditions[0] || {
    name: 'General Viral Syndrome',
    modelScore: 0.75,
    icd10Code: 'B34.9',
    confidenceCategory: 'Moderate',
  };

  const topScore = Math.round((topCondition.modelScore || 0.75) * 100);
  const layman = getConditionLaymanDetails(topCondition.name, bodyLocalization);

  // Home care steps from layman dictionary or storyline
  const careGuidance = layman.homeCare || [
    'Rest adequately and hydrate with warm water, broths, and electrolyte fluids',
    'Use warm steam inhalation or warm compress over affected areas twice daily',
    'Avoid strenuous exertion and monitor your temperature morning and evening',
  ];

  // Red flag warning signs
  const redFlags = layman.redFlags || [
    'Difficulty breathing, chest tightness, or blue-tinted lips',
    'Fever higher than 102°F (38.9°C) persisting longer than 3 days',
    'Severe headache accompanied by neck stiffness or sudden confusion',
    'Inability to tolerate liquids or keep fluids down for 24 hours',
  ];

  // Practical doctor questions for patient consultation
  const doctorQuestions = [
    `Does my symptom pattern strongly indicate ${layman.laymanTitle}, or should we test for bacterial causes?`,
    'Are there any over-the-counter medications or nasal sprays I should strictly avoid with my symptoms?',
    'What specific symptom changes should prompt me to visit urgent care instead of waiting?',
  ];

  const handleCopyQuestions = () => {
    const text = `QUESTIONS FOR MY DOCTOR (${layman.laymanTitle} Evaluation):\n` +
      doctorQuestions.map((q, i) => `${i + 1}. ${q}`).join('\n') +
      `\n\nGenerated by Patient Clinical Decision Support System`;
    navigator.clipboard.writeText(text);
    setCopiedQuestions(true);
    setTimeout(() => setCopiedQuestions(false), 2200);
  };

  const targetOrganName = bodyLocalization.targetOrgan || bodyLocalization.primaryRegion || layman.bodyConnection;

  return (
    <div className="flex flex-col h-full overflow-y-auto p-3.5 sm:p-5 space-y-4 bg-transparent">
      
      {/* 1. HERO CLINICAL ASSESSMENT CARD (Vibrant Emerald Palette: #10B981) */}
      <div className="rounded-2xl p-4 sm:p-6 bg-white border border-[#A7F3D0] shadow-xs space-y-4">
        
        {/* Top: Header + Synchronized ScoreGauge */}
        <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4">
          <div className="space-y-1.5 flex-1 min-w-0">
            <div className="flex items-center gap-2 flex-wrap">
              <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-[#ECFDF5] text-[#065F46] text-xs font-semibold font-display border border-[#A7F3D0]">
                <Stethoscope className="h-3.5 w-3.5 text-[#10B981]" />
                Primary Health Assessment
              </span>
              {layman.category && (
                <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full bg-[#D1FAE5] text-[#065F46] text-[11px] font-semibold border border-[#A7F3D0]">
                  {layman.category}
                </span>
              )}
            </div>

            <h3 className="text-xl sm:text-2xl font-display font-bold text-[#064E3B] tracking-tight pt-1">
              {layman.laymanTitle}
            </h3>
            
            <div className="flex items-center gap-2 flex-wrap text-xs pt-0.5">
              <span className="px-2 py-0.5 rounded-md bg-[#D1FAE5] text-[#065F46] font-medium border border-[#A7F3D0]/60">
                Everyday name: <strong className="text-[#064E3B] font-bold">{layman.plainName || layman.laymanTitle}</strong>
              </span>
              <span className="text-[#047857]/90">
                Medical classification: <strong className="text-[#064E3B] font-semibold">{topCondition.name}</strong>
              </span>
            </div>

            <p className="text-xs sm:text-sm text-[#065F46]/90 leading-relaxed pt-1 max-w-xl">
              {layman.explanation || storyline.patientOverview || topCondition.explanation}
            </p>
          </div>

          {/* Synchronized ScoreGauge — Vibrant Emerald Gradient (#10B981) */}
          <div className="p-2.5 bg-[#F0FDF4] border border-[#A7F3D0] rounded-2xl flex-shrink-0 self-start sm:self-auto flex flex-col items-center">
            <ScoreGauge
              value={topScore}
              size={88}
              strokeWidth={7}
              label="Match"
              confidence={topCondition.confidenceCategory || 'Moderate'}
              gradientColors={['#6EE7B7', '#10B981', '#047857']}
              gradientId="patientGaugeGrad"
              textColor="text-[#064E3B]"
            />
          </div>
        </div>

        {/* Interconnected Anatomical Link Banner with 1-Tap 3D Jump */}
        <div className="p-3 rounded-xl bg-[#ECFDF5] border border-[#A7F3D0] flex flex-col sm:flex-row sm:items-center justify-between gap-2.5 text-xs">
          <div className="flex items-start gap-2.5 min-w-0">
            <MapPin className="h-4 w-4 text-[#10B981] flex-shrink-0 mt-0.5" />
            <div className="space-y-0.5 min-w-0">
              <span className="font-semibold text-[#064E3B] block">
                Highlighted on 3D Body: {targetOrganName} ({bodyLocalization.primaryRegion || 'Target'} Region)
              </span>
              <p className="text-[11px] text-[#047857] leading-snug">
                {layman.anatomyExplanation}
              </p>
            </div>
          </div>
          {onView3D && (
            <button
              type="button"
              onClick={onView3D}
              className="inline-flex items-center justify-center gap-1.5 px-3 py-1.5 rounded-xl bg-[#10B981] hover:bg-[#059669] active:scale-95 text-white font-semibold text-xs shadow-xs transition-all cursor-pointer flex-shrink-0 self-start sm:self-auto font-display"
              title="Inspect 3D Anatomical Atlas"
            >
              <span>View in 3D Atlas</span>
              <ArrowRight className="h-3.5 w-3.5" />
            </button>
          )}
        </div>

      </div>

      {/* 2. THREE-CARD ACTIONABLE TRIAGE GRID (Mobile 1 col, Tablet/Desktop 3 col) */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-3.5 sm:gap-4 items-stretch">
        
        {/* Card A: Safe Home Care & Relief */}
        <div className="rounded-2xl p-4 sm:p-5 bg-white border border-[#A7F3D0] shadow-xs flex flex-col justify-between space-y-3">
          <div>
            <div className="flex items-center gap-2 mb-2.5">
              <div className="h-7 w-7 rounded-lg bg-[#ECFDF5] text-[#10B981] flex items-center justify-center flex-shrink-0 border border-[#A7F3D0]/60">
                <HeartHandshake className="h-4 w-4 text-[#059669]" />
              </div>
              <h4 className="font-display font-bold text-sm text-[#064E3B]">
                Safe Home Care
              </h4>
            </div>

            <p className="text-xs text-[#047857] mb-3 leading-snug">
              Simple non-prescription comfort measures:
            </p>

            <div className="space-y-2.5">
              {careGuidance.map((step, idx) => (
                <div key={idx} className="flex items-start gap-2 text-xs text-[#065F46]">
                  <div className="h-4 w-4 rounded-full bg-[#10B981] text-white flex items-center justify-center flex-shrink-0 mt-0.5 font-bold text-[10px]">
                    {idx + 1}
                  </div>
                  <span className="leading-snug">{step}</span>
                </div>
              ))}
            </div>
          </div>

          <p className="text-[10px] text-[#047857]/70 pt-2 border-t border-[#A7F3D0] italic">
            Non-pharmacological comfort measures. Do not begin prescription antibiotics without seeing a doctor.
          </p>
        </div>

        {/* Card B: When to See a Doctor (Red Flag Warning Signs) */}
        <div className="rounded-2xl p-4 sm:p-5 bg-[#FDF4F4] border border-[#F8D7DA] shadow-xs flex flex-col justify-between space-y-3">
          <div>
            <div className="flex items-center gap-2 mb-2.5">
              <div className="h-7 w-7 rounded-lg bg-[#FCE8E6] text-[#C0392B] flex items-center justify-center flex-shrink-0 border border-rose-200">
                <AlertTriangle className="h-4 w-4 text-[#C0392B]" />
              </div>
              <h4 className="font-display font-bold text-sm text-[#922B21]">
                When to See a Doctor
              </h4>
            </div>

            <p className="text-xs text-[#922B21] mb-3 leading-snug">
              Seek immediate medical evaluation if you notice:
            </p>

            <ul className="space-y-2">
              {redFlags.map((flag, idx) => (
                <li key={idx} className="flex items-start gap-2 text-xs text-[#78281F] font-medium">
                  <span className="h-1.5 w-1.5 rounded-full bg-[#C0392B] flex-shrink-0 mt-1.5" />
                  <span className="leading-snug">{flag}</span>
                </li>
              ))}
            </ul>
          </div>

          <div className="pt-2 border-t border-[#F8D7DA] flex items-center gap-1.5 text-[11px] text-[#922B21] font-medium">
            <ShieldAlert className="h-3.5 w-3.5 text-[#C0392B] flex-shrink-0" />
            <span>Call emergency care (911/112) for severe shortness of breath.</span>
          </div>
        </div>

        {/* Card C: Questions for Your Doctor (Patient Empowerment Tool) */}
        <div className="rounded-2xl p-4 sm:p-5 bg-white border border-[#A7F3D0] shadow-xs flex flex-col justify-between space-y-3">
          <div>
            <div className="flex items-center justify-between gap-2 mb-2.5">
              <div className="flex items-center gap-2">
                <div className="h-7 w-7 rounded-lg bg-[#ECFDF5] text-[#10B981] flex items-center justify-center flex-shrink-0 border border-[#A7F3D0]/60">
                  <ClipboardList className="h-4 w-4 text-[#059669]" />
                </div>
                <h4 className="font-display font-bold text-sm text-[#064E3B]">
                  Doctor Visit Questions
                </h4>
              </div>

              <button
                type="button"
                onClick={handleCopyQuestions}
                className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md text-[10px] font-semibold bg-[#10B981] hover:bg-[#059669] text-white shadow-2xs transition-colors cursor-pointer"
                title="Copy questions to clipboard"
              >
                {copiedQuestions ? <Check className="h-3 w-3 text-white" /> : <Copy className="h-3 w-3 text-white" />}
                <span>{copiedQuestions ? 'Copied' : 'Copy'}</span>
              </button>
            </div>

            <p className="text-xs text-[#047857] mb-3 leading-snug">
              Key questions to discuss with your healthcare provider:
            </p>

            <div className="space-y-2">
              {doctorQuestions.map((q, idx) => (
                <div key={idx} className="p-2.5 rounded-lg bg-[#F0FDF4] border border-[#A7F3D0] text-xs text-[#065F46] leading-snug">
                  <span className="font-bold text-[#064E3B] mr-1">Q{idx + 1}:</span>
                  {q}
                </div>
              ))}
            </div>
          </div>

          <p className="text-[10px] text-[#047857]/70 pt-2 border-t border-[#A7F3D0] italic">
            Taking written questions ensures all critical concerns get reviewed during consultation.
          </p>
        </div>

      </div>

      {/* 3. OTHER POTENTIAL CONDITIONS CONSIDERED (Clean Collapsible Accordion) */}
      {possibleConditions.length > 1 && (
        <div className="rounded-2xl p-3.5 sm:p-4 bg-white border border-[#A7F3D0] shadow-xs">
          <button
            type="button"
            onClick={() => setShowOtherConditions(!showOtherConditions)}
            className="w-full flex items-center justify-between text-left text-xs font-bold text-[#064E3B] cursor-pointer font-display"
          >
            <div className="flex items-center gap-2">
              <Activity className="h-4 w-4 text-[#10B981]" />
              <span>Other Potential Explanations Evaluated ({possibleConditions.length - 1})</span>
            </div>
            {showOtherConditions ? (
              <ChevronUp className="h-4 w-4 text-[#10B981]" />
            ) : (
              <ChevronDown className="h-4 w-4 text-[#10B981]" />
            )}
          </button>

          <AnimatePresence>
            {showOtherConditions && (
              <motion.div
                initial={{ opacity: 0, height: 0 }}
                animate={{ opacity: 1, height: 'auto' }}
                exit={{ opacity: 0, height: 0 }}
                className="overflow-hidden pt-3 space-y-2.5"
              >
                <p className="text-[11px] text-[#047857] leading-snug">
                  The clinical model also compared your symptoms against these secondary patterns:
                </p>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 pt-1">
                  {possibleConditions.slice(1, 5).map((cond, idx) => {
                    const condLayman = getConditionLaymanDetails(cond.name);
                    return (
                      <div
                        key={idx}
                        className="p-2.5 rounded-xl bg-[#F0FDF4] border border-[#A7F3D0] flex items-center justify-between text-xs"
                      >
                        <div className="truncate mr-2">
                          <span className="font-semibold text-[#064E3B] block truncate">
                            {condLayman.plainName || cond.name}
                          </span>
                          {condLayman.plainName && condLayman.plainName !== cond.name && (
                            <span className="text-[10px] text-[#047857]/80 block truncate">
                              Clinical: {cond.name}
                            </span>
                          )}
                        </div>
                        <span className="font-mono font-bold text-[#064E3B] bg-white px-2 py-0.5 rounded-md border border-[#A7F3D0] flex-shrink-0">
                          {Math.round((cond.modelScore || 0.2) * 100)}%
                        </span>
                      </div>
                    );
                  })}
                </div>
              </motion.div>
            )}
          </AnimatePresence>
        </div>
      )}

      {/* 4. CLINICAL SAFETY DISCLAIMER */}
      <div className="pt-1 text-center text-[11px] text-[#047857] flex items-center justify-center gap-1.5 pb-2">
        <Info className="h-3.5 w-3.5 text-[#10B981] flex-shrink-0" />
        <span>
          Clinical decision support tool for informational guidance only. Not a confirmed diagnosis. Always consult a licensed clinician.
        </span>
      </div>

    </div>
  );
}
